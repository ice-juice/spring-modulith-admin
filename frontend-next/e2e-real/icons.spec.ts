import { expect, test } from '@playwright/test'

test('configured permission icons survive real save/relogin and change the actual application button', async ({ page, browser, baseURL }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(process.env.SMA_E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL(url => url.pathname !== '/login')
  await page.goto('/iam/permissions')
  await page.getByRole('textbox', { name: '查询', exact: true }).fill('openapi:app:create')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.locator('.data-table tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '编辑 · 权限资源', exact: true })
  await editor.locator('#field-icon').click()
  const picker = page.getByRole('dialog', { name: '选择图标', exact: true })
  await picker.getByRole('textbox').fill('rocket')
  await picker.getByRole('button', { name: '火箭 · 3d:rocket', exact: true }).click()
  await picker.getByRole('button', { name: '使用此图标', exact: true }).click()
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await page.goto('/openapi/apps')
  await expect(page.getByRole('button', { name: '创建应用', exact: true }).locator('img')).toHaveAttribute('src', /icons\/3d\/rocket.webp$/)
  const context = await browser.newContext({ baseURL, locale: 'zh-CN' })
  try {
    const fresh = await context.newPage()
    await fresh.goto('/login')
    await fresh.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
    await fresh.getByLabel('密码', { exact: true }).fill(process.env.SMA_E2E_ADMIN_PASSWORD!)
    await fresh.getByRole('button', { name: '登录', exact: true }).click()
    await fresh.waitForURL(url => url.pathname !== '/login')
    await fresh.goto('/openapi/apps')
    const create = fresh.getByRole('button', { name: '创建应用', exact: true })
    await expect(create.locator('img')).toHaveAttribute('src', /icons\/3d\/rocket.webp$/)
    const token = await fresh.evaluate(() => sessionStorage.getItem('sma.access-token') || localStorage.getItem('sma.access-token'))
    const headers = { Authorization: 'Bearer ' + token }
    const response = await fresh.request.get(baseURL + '/api/iam/permissions', { headers })
    const row = (await response.json()).data.find((r: {permissionKey:string}) => r.permissionKey === 'openapi:app:create')
    const result = await fresh.request.put(baseURL + '/api/iam/permissions/' + row.id, { headers, data: { ...row, icon: 'none' } })
    expect((await result.json()).code).toBe(0)
    await fresh.reload()
    await expect(create.locator('img,svg')).toHaveCount(0)
    await create.click()
    await expect(fresh.getByRole('dialog')).toBeVisible()
  } finally { await context.close() }
})
