import { expect, test } from '@playwright/test'

test('global search uses real authorized keyword queries and opens a matching user', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(process.env.SMA_E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL(url => url.pathname !== '/login')
  await page.locator('header').getByRole('button', { name: '搜索', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '搜索', exact: true })
  await dialog.getByRole('button', { name: '全局', exact: true }).click()
  await dialog.getByRole('textbox').fill('admin')
  const users = dialog.getByRole('region', { name: '用户', exact: true })
  await expect(users.locator('[data-search-result]')).toHaveCount(1)
  await expect(users).toContainText('admin')
  await expect(dialog.getByText('此来源暂时无法查询，其他结果仍可使用。')).toHaveCount(0)
  await users.locator('[data-search-result]').click()
  await expect(page).toHaveURL(/\/iam\/users\?focus=\d+$/)
  await expect(page.getByRole('cell', { name: 'admin', exact: true })).toBeVisible()
  await expect(page.locator('.data-table tbody tr')).toHaveCount(1)
  await page.keyboard.press('Control+k')
  await dialog.getByRole('textbox').fill('no-match-global-fixture-987654321')
  await expect(dialog.getByRole('region', { name: '用户', exact: true }).getByText('没有匹配结果', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain('no-match-global-fixture')
})
