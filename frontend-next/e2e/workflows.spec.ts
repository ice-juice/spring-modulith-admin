test('application write is exclusive, rotation can be cancelled and credentials are removed on close', async ({ page }) => {
  const api = await fullApi(page)
  await login(page, '/openapi/apps')
  let finish: (() => void) | undefined
  await page.route(mockOrigin + '/api/openapi/apps/app1', async route => {
    if (route.request().method() !== 'PUT') return route.fallback()
    await new Promise<void>(resolve => { finish = resolve })
    await route.fallback()
  })
  const toggle = page.getByRole('switch', { name: '启用 · 测试应用', exact: true })
  await toggle.click()
  await expect(toggle).toBeDisabled()
  await expect(page.getByRole('button', { name: '轮换密钥', exact: true })).toBeDisabled()
  await expect.poll(() => !!finish).toBe(true)
  finish!()
  await expect(toggle).toBeEnabled()
  expect(api.writes.filter(write => write.path === '/openapi/apps/app1' && write.method === 'PUT')).toHaveLength(1)
  await page.getByRole('button', { name: '轮换密钥', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click()
  expect(api.writes.some(write => write.path.endsWith('/rotate'))).toBe(false)
  await page.getByRole('button', { name: '轮换密钥', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  const credentials = page.getByRole('dialog', { name: '应用凭据', exact: true })
  await expect(credentials.locator('#app-secret')).toHaveValue('fake-rotated-secret-only')
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('Denied')) } }) })
  await credentials.getByRole('button', { name: '复制密钥', exact: true }).click()
  await expect(page.getByText('复制失败，请手动选择并复制', { exact: true })).toBeVisible()
  await credentials.getByRole('button', { name: '取消', exact: true }).last().click()
  await expect(page.locator('#app-secret')).toHaveCount(0)
  await page.getByRole('button', { name: '测试应用', exact: true }).click()
  await expect(page.locator('#app-secret')).toHaveCount(0)
  expect(api.unmatched).toEqual([])
})

