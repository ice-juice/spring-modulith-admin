CREATE TABLE common_cache_task_gate (
    id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    created_at DATETIME(3) NOT NULL,
    created_by BIGINT NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    updated_by BIGINT NOT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_common_cache_task_gate_tenant (tenant_id),
    CONSTRAINT ck_common_cache_task_gate_active CHECK (deleted = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE common_cache_task (
    id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    public_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    portal VARCHAR(32) NOT NULL,
    tenant_generation BIGINT NOT NULL,
    action VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    reason VARCHAR(256) NOT NULL,
    frozen_json JSON NOT NULL,
    expires_at DATETIME(3) NOT NULL,
    cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
    fence BIGINT NOT NULL DEFAULT 0,
    lease_owner VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
    lease_until DATETIME(3) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    created_by BIGINT NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    updated_by BIGINT NOT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_common_cache_task_public (tenant_id,public_id),
    KEY ix_common_cache_task_owner (tenant_id,created_by,portal,created_at),
    KEY ix_common_cache_task_work (tenant_id,state,lease_until,id),
    KEY ix_common_cache_task_expiry (tenant_id,state,expires_at),
    CONSTRAINT ck_common_cache_task_state CHECK (state IN ('PREVIEW','QUEUED','RUNNING','SUCCEEDED','PARTIAL','FAILED','CANCELLED')),
    CONSTRAINT ck_common_cache_task_action CHECK (action IN ('CLEAR','PAUSE','RESUME','RESET_STATS')),
    CONSTRAINT ck_common_cache_task_fence CHECK (fence >= 0 AND tenant_generation > 0 AND deleted = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE common_cache_task_item (
    id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    ordinal INT NOT NULL,
    region VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    data_revision BIGINT NULL,
    control_version BIGINT NULL,
    failure_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
    created_at DATETIME(3) NOT NULL,
    created_by BIGINT NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    updated_by BIGINT NOT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_common_cache_task_item_region (tenant_id,task_id,region),
    UNIQUE KEY uk_common_cache_task_item_order (tenant_id,task_id,ordinal),
    CONSTRAINT ck_common_cache_task_item_state CHECK (state IN ('PENDING','APPLIED','DENIED','CHANGED','FAILED','CANCELLED')),
    CONSTRAINT ck_common_cache_task_item_order CHECK (ordinal >= 0 AND ordinal < 128 AND deleted = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
