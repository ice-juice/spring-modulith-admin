import { expect, test, type Locator, type Page } from '@playwright/test'
import { fullApi } from './full-api'
import { login } from './mock-api'

async function dragHorizontalThumb(page: Page, area: Locator) {
  await area.hover()
  const thumb = area.locator('[data-slot=scroll-area-thumb]').first()
  await expect(thumb).toBeVisible()
  const bounds = await thumb.boundingBox()
  if (!bounds) throw new Error('Missing scroll thumb')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 90, bounds.y + bounds.height / 2, { steps: 8 })
  await page.mouse.up()
}

test('theme has its own entry; language and time zone share a separate entry and persist independently', async ({ page }) => {
  const api = await fullApi(page)
  await login(page, '/')
  const header = page.locator('header')
  await header.getByRole('button', { name: '主题', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveCount(3)
  await expect(page.getByRole('menuitem', { name: 'English', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '深色', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(header.getByRole('button', { name: '主题', exact: true })).toHaveAttribute('title', '主题 · 深色')
  await header.getByRole('button', { name: '语言与时区', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveCount(3)
  await expect(page.getByRole('menuitem', { name: '深色', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '时区', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '时区', exact: true })
  await dialog.getByRole('button', { name: '时区', exact: true }).click()
  await page.getByRole('button', { name: 'UTC', exact: true }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await header.getByRole('button', { name: '语言与时区', exact: true }).click()
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await expect(header.getByRole('button', { name: 'Theme', exact: true })).toBeVisible()
  await page.reload()
  await expect(header.getByRole('button', { name: 'Language and time zone', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveClass(/dark/)
  expect(api.preferences).toMatchObject({ theme: 'dark', locale: 'en-US', timeZone: 'UTC' })
})

test('sidebar, business navigation, workspace tabs and database tables use overlay scrollbars without losing scrolling', async ({ page }) => {
  test.setTimeout(60000)
  const api = await fullApi(page), errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.text().includes('[Vue warn]')) errors.push(message.text()) })
  api.preferences.keepTabsAfterReload = true
  Object.assign(api.me, { navigation: Array.from({ length: 18 }, (_, i) => ({ id: 'nav' + i, name: '业务导航分组 ' + (i + 1), menuIds: ['org'] })) })
  await page.addInitScript(() => {
    const paths = ['/iam/users', '/iam/roles', '/iam/departments', '/iam/posts', '/iam/permissions', '/iam/navigation', '/config/dictionaries', '/config/parameters', '/file/files', '/message/notices', '/monitor/server', '/monitor/database']
    localStorage.setItem('sma.next.tabs.101', JSON.stringify(paths.map(path => ({ path, fallback: path }))))
  })
  await page.setViewportSize({ width: 1280, height: 620 })
  await login(page, '/')
  const sidebar = page.locator('[data-scroll-region=sidebar]'), viewport = sidebar.locator('[data-slot=scroll-area-viewport]')
  await expect.poll(() => viewport.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  expect(await viewport.evaluate(el => getComputedStyle(el).scrollbarWidth)).toBe('none')
  await viewport.hover()
  await page.mouse.wheel(0, 300)
  await expect.poll(() => viewport.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await expect(sidebar.locator('[data-slot=scroll-area-thumb]')).toBeVisible()
  await page.screenshot({ path: '../docs/frontend-next/images/scrollbars-navigation-light.png' })
  await page.mouse.move(1200, 600)
  await expect(sidebar.locator('[data-slot=scroll-area-scrollbar]')).toHaveCount(0)
  await page.locator('aside').getByRole('button', { name: '切换导航组', exact: true }).click()
  const navigation = page.locator('[data-scroll-region=business-navigation]')
  await expect(page.getByRole('menuitemradio')).toHaveCount(19)
  await navigation.hover()
  await page.mouse.wheel(0, 320)
  await expect.poll(() => navigation.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  const tabs = page.locator('[data-scroll-region=work-tabs] [data-slot=scroll-area-viewport]')
  await tabs.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => tabs.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
  api.preferences.theme = 'dark'
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/monitor/database')
  await expect(page.getByRole('button', { name: 'iam_user', exact: true })).toBeVisible()
  expect(await page.locator('[data-scroll-region=database-tables]').evaluate(el => el.clientHeight)).toBeLessThan(200)
  const table = page.locator('[data-scroll-region=table]').first(), tableViewport = table.locator('[data-slot=scroll-area-viewport]')
  await expect.poll(() => tableViewport.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  expect(await tableViewport.evaluate(el => getComputedStyle(el).scrollbarWidth)).toBe('none')
  await dragHorizontalThumb(page, table)
  await expect.poll(() => tableViewport.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
  await tableViewport.focus()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../docs/frontend-next/images/scrollbars-database-dark.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(errors).toEqual([])
  expect(api.unmatched).toEqual([])
})
