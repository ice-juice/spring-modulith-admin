import { expect, test, type APIResponse } from '@playwright/test'
import type { TenantEntryDto } from '../src/lib/tenant-branding'

async function data<T>(response: APIResponse): Promise<T> {
  expect(response.status()).toBe(200)
  const body = await response.json()
  expect(body.code).toBe(0)
  return body.data as T
}
test('real brand editor uploads, previews, publishes policies and rolls back without altering the draft', async ({ page, browser, baseURL }, info) => {
  test.setTimeout(180000)
  const password = process.env.SMA_E2E_ADMIN_PASSWORD
  if (!password) throw new Error('Use the isolated backend runner.')
  await page.goto('/tenant/brand')
  await page.getByLabel('用户名', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/tenant/brand')
  await expect(page.locator('#brand-name')).toBeEnabled({ timeout: 15000 })
  await page.getByRole('button', { name: '皮肤', exact: true }).click()
  await page.getByRole('menuitemradio', { name: '青瓷绿', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'celadon')
  const token = await page.evaluate(() => sessionStorage.getItem('sma.access-token') || localStorage.getItem('sma.access-token'))
  const headers = { Authorization: 'Bearer ' + token, Origin: baseURL! }
  await page.locator('#brand-name').fill('P10 第一版品牌')
  await page.getByRole('tab', { name: '登录页', exact: true }).click()
  await page.getByRole('button', { name: '全屏背景', exact: true }).click()
  await page.locator('#brand-title-zh').fill('欢迎使用租户工作台')
  await page.getByRole('tab', { name: '版权与备案', exact: true }).click()
  await page.locator('#brand-copyright').fill('P10 品牌主体')
  await page.locator('#brand-year').fill('2026')
  await page.locator('#brand-icp').fill('P10 测试备案')
  await page.getByRole('tab', { name: '品牌图片', exact: true }).click()
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 32
    const context = canvas.getContext('2d')!; context.fillStyle = '#6753bd'; context.fillRect(0, 0, 64, 32)
    return canvas.toDataURL('image/png').split(',')[1]!
  })
  const image = { name: 'brand-image.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') }
  await page.locator('input[type=file][aria-label="浅色 Logo"]').setInputFiles(image)
  await expect(page.getByText('已配置图片，可预览效果', { exact: true })).toHaveCount(1)
  await page.locator('input[type=file][aria-label="登录背景"]').setInputFiles(image)
  await expect(page.getByText('已配置图片，可预览效果', { exact: true })).toHaveCount(2)
  await page.getByRole('tab', { name: '外观', exact: true }).click()
  await page.locator('#brand-skin').selectOption('amber')
  await page.locator('#brand-personal-skin').click()
  await expect(page.locator('#brand-personal-skin')).toHaveAttribute('aria-checked', 'false')
  await page.getByRole('button', { name: '预览登录页', exact: true }).click()
  const preview = page.frameLocator('iframe[title="预览登录页"]')
  await expect(preview.locator('[data-login-template]')).toHaveAttribute('data-login-template', 'login3')
  await expect(preview.getByRole('img', { name: 'P10 第一版品牌', exact: true })).toHaveAttribute('src', /^data:image\/png;base64,/)
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'celadon')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已保存，尚未发布。', { exact: true })).toBeVisible()
  expect((await data<TenantEntryDto>(await page.request.get('/api/tenant/entry'))).branding.identity.systemName).not.toBe('P10 第一版品牌')
  await page.getByRole('button', { name: '发布品牌', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('品牌已发布。', { exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'amber')
  await expect(page.getByRole('button', { name: '皮肤', exact: true })).toBeDisabled()
  const first = await data<TenantEntryDto>(await page.request.get('/api/tenant/entry'))
  expect(first.branding.login.templateId).toBe('login3')
  expect(first.branding.assets.LOGO_LIGHT).toBeTruthy()
  const visitorContext = await browser.newContext({ locale: 'zh-CN' })
  const visitor = await visitorContext.newPage()
  await visitor.goto(baseURL! + '/login')
  await expect(visitor.locator('[data-login-template]')).toHaveAttribute('data-login-template', 'login3')
  await expect(visitor.locator('.branding-footer')).toContainText('P10 品牌主体')
  await expect(visitor.getByRole('img', { name: 'P10 第一版品牌', exact: true })).toHaveAttribute('src', first.branding.assets.LOGO_LIGHT!)
  await visitorContext.close()
  await page.getByRole('tab', { name: '品牌名称', exact: true }).click()
  await page.locator('#brand-name').fill('P10 第二版草稿')
  await page.getByRole('tab', { name: '外观', exact: true }).click()
  await page.locator('#brand-personal-skin').click()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已保存，尚未发布。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '发布品牌', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'celadon')
  await page.getByRole('tab', { name: '发布历史', exact: true }).click()
  await page.locator('article').filter({ hasText: 'P10 第一版品牌' }).getByRole('button', { name: '回退到此版本' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('已创建回退发布，草稿保持不变。', { exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'amber')
  const current = await data<TenantEntryDto>(await page.request.get('/api/tenant/entry'))
  expect(current.branding.identity.systemName).toBe('P10 第一版品牌')
  expect(current.branding.revisionId).not.toBe(first.branding.revisionId)
  expect((await data<{ content: { identity: { systemName: string } } }>(await page.request.get('/api/tenant/brands/draft', { headers }))).content.identity.systemName).toBe('P10 第二版草稿')
  await page.screenshot({ path: info.outputPath('brand-management-real.png'), fullPage: true })
})
