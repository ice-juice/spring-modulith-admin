import { expect, test } from '@playwright/test'
import type { DomainRecord } from '../src/features/tenant/directory'

test('real platform operator registers a tenant and domain, rotates a challenge and cannot enable without evidence', async ({ page, baseURL }, info) => {
  test.setTimeout(180000)
  const password = process.env.SMA_E2E_ADMIN_PASSWORD
  if (!password || process.env.SMA_E2E_PLATFORM_OPERATOR !== '1') throw new Error('Use the isolated runner with SMA_E2E_PLATFORM_OPERATOR=1.')
  const code = 'p10-' + Date.now(), tenantName = 'P10 目录验收 ' + code
  await page.goto('/tenant/tenants')
  await page.getByLabel('用户名', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/tenant/tenants')
  await expect(page.getByRole('button', { name: '登记租户', exact: true })).toBeEnabled({ timeout: 20000 })
  await page.getByRole('button', { name: '登记租户', exact: true }).click()
  await page.getByLabel('租户编码', { exact: true }).fill(code)
  await page.getByLabel('租户名称', { exact: true }).fill(tenantName)
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  const tenantRow = page.locator('tr').filter({ hasText: tenantName })
  await expect(tenantRow.getByText('待准备', { exact: true })).toBeVisible()
  await tenantRow.getByRole('button', { name: '修改状态', exact: true }).click()
  await page.getByLabel('状态', { exact: true }).selectOption('ACTIVE')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(tenantRow.getByText('已启用', { exact: true })).toBeVisible()
  await page.goto('/tenant/domains')
  await expect(page.locator('#domain-owner')).toBeEnabled({ timeout: 15000 })
  const tenantId = await page.locator('#domain-owner option').filter({ hasText: tenantName }).getAttribute('value')
  expect(tenantId).toMatch(/^\d+$/)
  await page.locator('#domain-owner').selectOption(tenantId!)
  await expect(page.getByRole('button', { name: '登记域名', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '登记域名', exact: true }).click()
  await page.getByLabel('域名', { exact: true }).fill(code + '.example.invalid')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name: code + '.example.invalid' })).toBeVisible()
  await expect(page.getByRole('button', { name: '启用域名', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '生成挑战', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('_sma-tenant.' + code + '.example.invalid', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '运行域名检查', exact: true })).toBeDisabled()
  const token = await page.evaluate(() => sessionStorage.getItem('sma.access-token') || localStorage.getItem('sma.access-token'))
  const headers = { Authorization: 'Bearer ' + token, Origin: baseURL! }
  const before = await page.request.get('/api/tenant/domains?tenantId=' + tenantId, { headers })
  expect(before.ok()).toBe(true)
  const row = (await before.json()).data[0] as DomainRecord
  expect(row.status).toBe('PENDING'); expect(row.activationReady).toBe(false); expect(row.challengeValue).toMatch(/^sma-tenant-v1=/)
  // Respect the deployed 500ms object-write cooldown so this negative assertion reaches the evidence gate.
  await page.waitForTimeout(550)
  const rejected = await page.request.put('/api/tenant/domains/' + row.id + '/enabled', { headers: { ...headers, 'Idempotency-Key': crypto.randomUUID() }, data: { expectedVersion: row.version, enabled: true } })
  const body = await rejected.json()
  expect(body.code).not.toBe(0)
  expect(body.error).toBe('tenant.error.domain-verification-required')
  const after = await page.request.get('/api/tenant/domains/' + row.id, { headers })
  expect((await after.json()).data.status).toBe('PENDING')
  await page.screenshot({ path: info.outputPath('tenant-domain-real.png') })
})
