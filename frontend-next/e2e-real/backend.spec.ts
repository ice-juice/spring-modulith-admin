import { expect, test } from '@playwright/test'
test('real isolated backend: accounts, authorization, messages, realtime push, files and application credentials', async ({ page, browser }) => {
  const password = process.env.SMA_E2E_ADMIN_PASSWORD
  if (!password) throw new Error('Run through scripts/run-real-e2e.mjs; production credentials are never used.')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.text().includes('[intlify]') || message.text().includes('[Vue warn]')) errors.push(message.text()) })
  await page.goto('/login')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL(url => url.pathname !== '/login')
  await expect(page.locator('main h1')).toBeVisible()
  await page.goto('/iam/posts')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('前端验收岗位')
  await dialog.getByRole('textbox', { name: '编码', exact: true }).fill('NEXT_E2E')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('cell', { name: '前端验收岗位', exact: true })).toBeVisible()
  await page.goto('/iam/users')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await dialog.getByRole('textbox', { name: '用户名', exact: true }).fill('next_e2e_member')
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('前端验收成员')
  await dialog.getByLabel('初始密码').fill('IsolatedMemberPassword!2026')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('cell', { name: 'next_e2e_member', exact: true })).toBeVisible()
  const memberContext = await browser.newContext({ locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
  const member = await memberContext.newPage()
  member.on('pageerror', error => errors.push(error.message))
  await member.goto('http://127.0.0.1:5174/login')
  await member.getByRole('textbox', { name: '用户名', exact: true }).fill('next_e2e_member')
  await member.getByLabel('密码', { exact: true }).fill('IsolatedMemberPassword!2026')
  await member.getByRole('button', { name: '登录', exact: true }).click()
  await member.waitForURL(url => url.pathname !== '/login')
  await member.goto('http://127.0.0.1:5174/iam/users')
  await expect(member.getByRole('heading', { name: '没有访问权限', exact: true })).toBeVisible()
  await member.goto('http://127.0.0.1:5174/message/inbox')
  await expect(member.getByText('实时同步', { exact: true })).toBeVisible()
  await page.goto('/iam/roles')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('前端验收角色')
  await dialog.getByRole('textbox', { name: '编码', exact: true }).fill('NEXT_ROLE')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const roleRow = page.getByRole('row').filter({ hasText: '前端验收角色' })
  await roleRow.getByRole('button', { name: '角色授权', exact: true }).click()
  await dialog.getByRole('checkbox').first().click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await roleRow.getByRole('button', { name: '角色授权', exact: true }).click()
  await expect(dialog.getByRole('checkbox').first()).toBeChecked()
  await dialog.getByRole('button', { name: '取消', exact: true }).last().click()
  await page.goto('/message/notices')
  await page.getByRole('button', { name: '发布通知', exact: true }).click()
  await dialog.getByRole('textbox', { name: '标题', exact: true }).fill('前端真实联调通知')
  await dialog.getByRole('textbox', { name: '内容', exact: true }).fill('此通知仅存在于独立测试数据库。')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '前端真实联调通知', exact: true })).toBeVisible()
  await expect(member.getByRole('button', { name: '前端真实联调通知', exact: true })).toBeVisible()
  await page.goto('/message/inbox?tab=tasks')
  await page.getByRole('button', { name: '新建待办', exact: true }).click()
  await dialog.getByRole('textbox', { name: '标题', exact: true }).fill('前端真实联调待办')
  await dialog.locator('#task-due').fill('2030-11-10T15:30')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '前端真实联调待办', exact: true })).toBeVisible()
  await page.goto('/message/inbox?tab=private')
  await page.getByRole('button', { name: '写私信', exact: true }).click()
  await dialog.getByRole('button', { name: '收信人', exact: true }).click()
  await page.getByRole('button', { name: '前端验收成员', exact: true }).click()
  await dialog.getByRole('textbox', { name: '内容', exact: true }).fill('仅发送给本次创建的隔离测试账号。')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('tab', { name: '发件箱', exact: true }).click()
  await expect(page.getByRole('button', { name: '仅发送给本次创建的隔离测试账号。', exact: true })).toBeVisible()
  await page.goto('/file/files')
  await page.locator('input[type=file]').setInputFiles({ name: 'next-e2e.txt', mimeType: 'text/plain', buffer: Buffer.from('Independent frontend verification\n') })
  await expect(page.getByRole('button', { name: 'next-e2e.txt', exact: true })).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载', exact: true }).first().click()
  expect((await downloaded).suggestedFilename()).toBe('next-e2e.txt')
  await page.goto('/openapi/apps')
  await page.getByRole('button', { name: '创建应用', exact: true }).click()
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('前端验收应用')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '应用凭据', exact: true })).toBeVisible()
  await expect(page.locator('#app-id')).not.toHaveValue('')
  await expect(page.locator('#app-secret')).not.toHaveValue('')
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).last().click()
  await page.goto('/monitor/database')
  await expect(page.getByRole('heading', { name: '数据库文档', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '刷新', exact: true })).toBeEnabled({ timeout: 60000 })
  await expect(page.getByRole('button', { name: 'iam_user', exact: true })).toBeVisible()
  await memberContext.close()
  expect(errors).toEqual([])
})
