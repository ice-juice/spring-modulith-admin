import { expect, test } from '@playwright/test'
test('design system: table, form validation, focus, theme, locale and responsive samples', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.text().includes('[intlify]')) errors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/dev/components')
  await expect(page.getByRole('heading', { name: '用户管理样板' })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'chen.zhiyuan', exact: true })).toBeVisible()
  await page.screenshot({ path: '../docs/frontend-next/images/users-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('此项不能为空')
  await page.getByLabel('名称', { exact: true }).fill('测试用户')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('保存成功', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '角色授权样板', exact: true }).click()
  await page.getByRole('button', { name: '全部展开', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '新增', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: '新增', exact: true }).click()
  const selection = await page.getByText(/已选择 .* 项/).textContent()
  await page.getByPlaceholder('搜索节点').fill('查询')
  await expect(page.getByText(selection!, { exact: true })).toBeVisible()
  await page.getByPlaceholder('搜索节点').clear()
  await page.screenshot({ path: '../docs/frontend-next/images/roles-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '工作台样板', exact: true }).click()
  await page.screenshot({ path: '../docs/frontend-next/images/workspace-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '显示设置', exact: true }).click()
  await page.getByRole('menuitem', { name: '深色', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('button', { name: '显示设置', exact: true }).click()
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Workspace sample' })).toBeVisible()
  await page.screenshot({ path: '../docs/frontend-next/images/workspace-dark-english.png', fullPage: true })
  for (const width of [1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  }
  await page.screenshot({ path: '../docs/frontend-next/images/workspace-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
test('login handles public settings and empty submission without contacting the login endpoint', async ({ page }) => {
  let loginRequests = 0
  await page.route('**/api/config/parameters/public', route => route.fulfill({ json: { code: 0, data: { 'login.captchaEnabled': 'false', 'system.name': 'SMA' } } }))
  await page.route('**/api/auth/login', route => { loginRequests++; return route.fulfill({ status: 500 }) })
  await page.goto('/login')
  await expect(page.getByLabel('用户名', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '登录', exact: true }).click()
  expect(loginRequests).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
})
test('dirty editor cancellation opens a separate confirmation and keeps the draft when declined', async ({ page }) => {
  await page.goto('/dev/components')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('未保存草稿')
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).last().click()
  const confirmation = page.getByRole('alertdialog')
  await expect(confirmation).toContainText('未保存的修改')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('未保存草稿')
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).last().click()
  await confirmation.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
