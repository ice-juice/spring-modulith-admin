import { expect, test } from '@playwright/test'
import { login, mockApi, roleId, userId } from './mock-api'
import { fullApi } from './full-api'
test('user form keeps failed drafts, retries once on explicit submission and preserves string IDs', async ({ page }) => {
  const api = await mockApi(page), errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await expect(page).toHaveURL(/\/iam\/users$/)
  await expect(page.getByRole('button', { name: '全部展开', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '全部收起', exact: true })).toHaveCount(0)
  await expect(page.getByRole('cell', { name: 'test.user', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const name = dialog.getByRole('textbox', { name: '名称', exact: true })
  await expect(name).toHaveValue('测试成员')
  await name.fill('修改后的成员')
  api.failNextUserSave()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('模拟保存失败')
  await expect(name).toHaveValue('修改后的成员')
  expect(api.writes.filter(w => w.path === '/iam/users/' + userId)).toHaveLength(1)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('cell', { name: '修改后的成员', exact: true })).toBeVisible()
  expect(api.writes.filter(w => w.path === '/iam/users/' + userId)).toHaveLength(2)
  expect(api.failures).toEqual([]); expect(errors).toEqual([])
})
test('role authorization uses independent checks and preserves hidden choices under search', async ({ page }) => {
  const api = await mockApi(page)
  await login(page, '/iam/roles')
  const dialog = page.locator('[data-role-permissions]')
  await dialog.getByRole('button', { name: '全部展开', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '组织管理', exact: true })).toBeChecked()
  await dialog.getByPlaceholder('搜索节点').fill('查看用户')
  await dialog.getByRole('checkbox', { name: '查看用户', exact: true }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('与上次读取或保存一致')
  const write = api.writes.find(w => w.method === 'PUT' && w.path === '/iam/roles/' + roleId + '/permissions')
  expect(write?.body.permissionIds).toEqual(['menu', 'write'])
  expect(api.failures).toEqual([])
})

test('permission filters combine type, status and keyword and reveal matching descendants', async ({ page }) => {
  const api = await fullApi(page)
  const permissions = [
    { id: 'directory', parentId: '0', name: '业务目录', permissionKey: 'biz', type: 'DIRECTORY', enabled: true },
    { id: 'menu', parentId: 'directory', name: '订单菜单', permissionKey: 'biz:order', type: 'MENU', enabled: true },
    { id: 'create', parentId: 'menu', name: '创建订单', permissionKey: 'biz:order:create', type: 'BUTTON', enabled: true },
    { id: 'delete', parentId: 'menu', name: '删除订单', permissionKey: 'biz:order:delete', type: 'BUTTON', enabled: false },
    { id: 'logic', parentId: 'directory', name: '订单数据范围', permissionKey: 'biz:order:scope', type: 'LOGIC', enabled: false },
  ]
  await page.route('**/api/iam/permissions?*', route => route.fulfill({ json: { code: 0, data: permissions } }))
  await login(page, '/iam/permissions')
  const rows = page.locator('.data-table tbody tr')
  const type = page.getByRole('combobox', { name: '资源类型', exact: true })
  const status = page.getByRole('combobox', { name: '状态', exact: true })
  const expandAll = page.getByRole('button', { name: '全部展开', exact: true })
  const collapseAll = page.getByRole('button', { name: '全部收起', exact: true })
  await expect(rows).toHaveCount(5)
  await expect(expandAll).toBeDisabled()
  await collapseAll.click()
  await expect(rows).toHaveCount(1)
  await expect(collapseAll).toBeDisabled()
  await page.getByRole('button', { name: '业务目录', exact: true }).click()
  await expect(rows).toHaveCount(3)
  await expect(page.getByRole('button', { name: '订单菜单', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expandAll.click()
  await expect(rows).toHaveCount(5)
  await expect(page.getByRole('button', { name: '订单菜单', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await status.selectOption('enabled')
  await expect(rows).toHaveCount(3)
  await collapseAll.click()
  await expect(rows).toHaveCount(1)
  await expandAll.click()
  await expect(rows).toHaveCount(3)
  await expect(status).toHaveValue('enabled')
  await status.selectOption('')
  await expect(rows).toHaveCount(5)
  await page.getByRole('button', { name: '业务目录', exact: true }).click()
  await expect(rows).toHaveCount(1)
  await type.selectOption('BUTTON')
  await expect(rows).toHaveCount(2)
  await expect(expandAll).toBeDisabled()
  await expect(collapseAll).toBeDisabled()
  await status.selectOption('disabled')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('删除订单')
  await status.selectOption('enabled')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('创建订单')
  await status.selectOption('')
  const keyword = page.getByRole('textbox', { name: '查询', exact: true })
  await keyword.fill('BIZ:ORDER:DELETE')
  await keyword.press('Enter')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('删除订单')
  await status.selectOption('enabled')
  await expect(page.getByText('暂无数据', { exact: true })).toBeVisible()
  await expect(expandAll).toBeDisabled()
  await expect(collapseAll).toBeDisabled()
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(type).toHaveValue('')
  await expect(status).toHaveValue('')
  await expect(keyword).toHaveValue('')
  await expect(rows).toHaveCount(5)
  for (const [value, name] of [['DIRECTORY', '业务目录'], ['MENU', '订单菜单'], ['LOGIC', '订单数据范围']]) {
    await type.selectOption(value!)
    await expect(rows).toHaveCount(1)
    await expect(rows).toContainText(name!)
  }
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(rows).toHaveCount(1)
  await expect(type).toHaveValue('LOGIC')
  for (const theme of ['light', 'dark']) {
    api.preferences.theme = theme
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 900 })
      await page.reload()
      await expect(rows).toHaveCount(5)
      await collapseAll.click()
      await expect(rows).toHaveCount(1)
      await expandAll.focus()
      await page.keyboard.press('Enter')
      await expect(rows).toHaveCount(5)
      await page.screenshot({ path: `test-results/permission-tree-${theme}-${width}.png` })
      await type.selectOption('BUTTON')
      await status.selectOption('disabled')
      await expect(rows).toHaveCount(1)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true)
      await type.focus()
      await page.keyboard.press('Tab')
      await expect(status).toBeFocused()
      await page.screenshot({ path: `test-results/permission-filters-${theme}-${width}.png` })
    }
  }
  api.preferences.locale = 'en-US'
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Resource type', exact: true })).toContainText('All types')
  await expect(page.getByRole('combobox', { name: 'Status', exact: true })).toContainText('All statuses')
  await expect(page.getByRole('button', { name: 'Expand all', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Collapse all', exact: true }).click()
  await expect(rows).toHaveCount(1)
  expect(api.unmatched).toEqual([])
  expect(api.writes.filter(write => write.path.startsWith('/iam/permissions'))).toEqual([])
})
