  await page.getByRole('button', { name: '写私信', exact: true }).click()
  await dialog.getByRole('button', { name: '收信人', exact: true }).click()
  await page.getByRole('button', { name: '前端验收成员', exact: true }).click()
  await dialog.getByRole('textbox', { name: '内容', exact: true }).fill('仅发送给本次创建的隔离测试账号。')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('tab', { name: '发件箱', exact: true }).click()
  await expect(page.getByRole('button', { name: '仅发送给本次创建的隔离测试账号。', exact: true })).toBeVisible()
