test('iframe routes resolve authorized menu IDs and reject unsafe or unknown targets', async ({ page }) => {
  const api = await fullApi(page)
  const template = api.me.menus[0]!.children[0]!
  api.me.menus[0]!.children.push({ ...template, id: 'safe-frame', name: '受控嵌入页', openMode: 'IFRAME', path: '/isolated-frame' }, { ...template, id: 'unsafe-frame', name: '不可用嵌入页', openMode: 'IFRAME', path: 'javascript:alert(1)' })
  await page.route(mockOrigin + '/isolated-frame', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Isolated frame</title><p>Local frame fixture</p>' }))
  await login(page, '/frame/safe-frame')
  await expect(page.locator('iframe[title="受控嵌入页"]')).toHaveAttribute('src', '/isolated-frame')
  await expect(page.frameLocator('iframe').getByText('Local frame fixture')).toBeVisible()
  for (const id of ['unsafe-frame', 'unknown']) {
    await page.goto('/frame/' + id)
    await expect(page.locator('iframe')).toHaveCount(0)
    await expect(page.locator('main')).toContainText('没有访问权限')
  }
})

